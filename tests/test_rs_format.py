class TestRsRoundtrip(unittest.TestCase):
    def _check(self, sample):
        doc = parse_rs(sample)
        out = format_rs(doc)  # CRLF
        self.assertEqual(out.splitlines(), sample.splitlines())

    def test_rotary_rs_byte_identical(self):
        self._check(SAMPLE_RS)

    def test_tilt_rsk_byte_identical(self):
        self._check(SAMPLE_RSK)

    def test_crlf_and_trailing_newline(self):
        out = format_rs(parse_rs(SAMPLE_RS))
        self.assertIn("\r\n", out)
        self.assertTrue(out.endswith("\r\n"))

    def test_header_fields(self):
        doc = parse_rs(SAMPLE_RSK)
        self.assertEqual(doc["model"], "RTT-315")
        self.assertEqual(doc["close"], "ZC")
        self.assertEqual(doc["date"], "2026/06/12")
        self.assertEqual(doc["operator"], "simizu")
        self.assertEqual(len(doc["blocks"]), 6)
        self.assertEqual(doc["repeats"], 7)


class TestDataToRsDoc(unittest.TestCase):
    def test_degree_to_arcsec_conversion(self):
        # 指令10°、CW測定 = 10° + 2"・1"、CCW = 10° + 1.5"
        rep_points = [10.0]
        rep_data = {
            ("cw", 0): [10.0 + 2.0 / 3600.0, 10.0 + 1.0 / 3600.0],
            ("ccw", 0): [10.0 + 1.5 / 3600.0, 10.0 + 1.5 / 3600.0],
        }
        doc = data_to_rs_doc(rep_points, rep_data, model="X", close="",
                             date="2026/01/01", operator="t", repeats=2)
        text = format_rs(doc)
        lines = text.splitlines()
        # 3行目=ブロック1,回2
        self.assertEqual(lines[2], "1,2")
        # データ行（偏差["]に変換されている）
        self.assertEqual(lines[-2], "1.000000,2.000000,1.500000")
        self.assertEqual(lines[-1], "2.000000,1.000000,1.500000")


